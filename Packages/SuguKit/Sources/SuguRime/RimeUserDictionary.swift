import Foundation
import SuguCore

/// Sugu's Chinese learned and user words as librime's user dictionary, so
/// they take part in librime's sentences and not only when typed alone.
///
/// The file is generated from the learned store and opened read-only
/// (`db_class: stabledb`): librime never learns into it, so the store stays
/// the one place words live, and deleting a word there removes it here on
/// the next write.
public enum RimeUserDictionary {
    public static let name = "sugu_learned"

    public struct Word: Sendable, Hashable {
        public var reading: String
        public var text: String
        public var count: Int

        public init(reading: String, text: String, count: Int) {
            self.reading = reading
            self.text = text
            self.count = count
        }
    }

    public static func file(in userDirectory: URL) -> URL {
        userDirectory.appendingPathComponent("\(name).txt")
    }

    /// Longest word written, in characters: librime looks user phrases up
    /// for sentences up to five syllables, and Sugu matches longer commits
    /// by their whole reading itself.
    static let maximumLength = 5

    /// Readings per word, at most: more mean the reading was ambiguous.
    static let maximumReadings = 2

    /// Words written, at most. librime parses the file on the main thread
    /// whenever a session opens, about 1 ms per thousand lines; the rest
    /// still match by their whole reading.
    static let maximumWords = 3_000

    /// The table, from `words` in order of priority: word, syllables and
    /// use count per line. Words of one
    /// character are left out, so a single choice does not reorder a
    /// common syllable in every sentence; so are words whose keys do not
    /// read as one syllable per character under the scheme in use, or,
    /// for imported pinyin, under full pinyin.
    public static func table(for words: [Word], decoder: PinyinDecoder, fullPinyin: PinyinDecoder?) -> String {
        var lines = Set<String>()
        var written = 0
        for word in words where (2...maximumLength).contains(word.text.count) && word.text.allSatisfy(\.isHan) {
            guard written < maximumWords else { break }
            var readings = decoder.syllables(typedAs: word.reading, count: word.text.count, limit: maximumReadings)
            if readings.isEmpty, let fullPinyin {
                readings = fullPinyin.syllables(typedAs: word.reading, count: word.text.count, limit: maximumReadings)
            }
            if !readings.isEmpty { written += 1 }
            for syllables in readings {
                lines.insert("\(word.text)\t\(syllables.joined(separator: " "))\t\(commits(uses: word.count))")
            }
        }
        return "# Generated by Sugu from its learned words; rewritten on every change.\n"
            + lines.sorted().map { $0 + "\n" }.joined()
    }

    /// librime scores a read-only user phrase from its commit count alone,
    /// on a scale where one commit is next to nothing; 2×10⁸ per use puts
    /// a word used once among common words, enough to take its place in a
    /// sentence. Counted up to 9 uses: librime adds one to the count as a
    /// 32-bit integer, and from 2×10⁹ its formula changes branch and the
    /// weight stops growing.
    static func commits(uses: Int) -> Int {
        min(max(1, uses), 9) * 200_000_000
    }

    /// Writes `table` unless the file already holds it, keeping the file
    /// out of backups like the store. Returns whether it wrote.
    @discardableResult
    public static func write(_ table: String, in userDirectory: URL) throws -> Bool {
        var url = file(in: userDirectory)
        if (try? String(contentsOf: url, encoding: .utf8)) == table { return false }
        try FileManager.default.createDirectory(at: userDirectory, withIntermediateDirectories: true)
        try table.write(to: url, atomically: true, encoding: .utf8)
        try? FileManager.default.setAttributes([.protectionKey: FileProtectionType.completeUntilFirstUserAuthentication], ofItemAtPath: url.path)
        var values = URLResourceValues()
        values.isExcludedFromBackup = true
        try? url.setResourceValues(values)
        return true
    }

    /// Creates an empty table when there is none: librime opens the user
    /// dictionary with each session, and a missing file would send it to
    /// recover a database it does not own.
    static func ensureExists(in userDirectory: URL) throws {
        guard !FileManager.default.fileExists(atPath: file(in: userDirectory).path) else { return }
        try write(table(for: [], decoder: PinyinDecoder(syllables: [], rules: []), fullPinyin: nil), in: userDirectory)
    }
}

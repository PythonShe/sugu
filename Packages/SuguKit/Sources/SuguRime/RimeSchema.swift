import Foundation
import SuguCore

/// Sugu's generated librime schema. Users never edit YAML; settings map to
/// this structure and Sugu writes `sugu.schema.yaml` into the user data
/// directory, where it overrides the bundled default.
public struct RimeSchema: Sendable, Equatable {
    public static let schemaID = "sugu"
    public static let dictionaryName = "sugu"
    /// Dictionary built from a downloaded rime-ice in the user directory.
    public static let rimeIceDictionaryName = "sugu_ice"
    /// Folder in the user directory that holds rime-ice's tables.
    public static let rimeIceFolder = "rime-ice"
    /// rime-ice tables imported into `sugu_ice`, in rime-ice's order.
    public static let rimeIceTables = ["8105", "base", "ext", "tencent", "others"]
    /// Name of the wanxiang grammar model loaded by librime-octagram. The
    /// dictionary is Simplified, and the model scores sentences before the
    /// script filter runs, so the Simplified model serves every script.
    public static let grammarLanguage = "wanxiang-lts-zh-hans"

    /// Zhuyin reads syllables as pinyin with their tone (`ni3`), which
    /// Sugu's Zhuyin engine types; the scheme and fuzzy pinyin then apply
    /// to pinyin only.
    public var keyboard: ChineseKeyboard
    public var scheme: PinyinScheme
    public var fuzzy: Set<FuzzyPinyin>
    public var useGrammar: Bool
    public var dictionary: ChineseDictionary

    public init(keyboard: ChineseKeyboard = .pinyin, scheme: PinyinScheme = .fullPinyin, fuzzy: Set<FuzzyPinyin> = [], useGrammar: Bool = false, dictionary: ChineseDictionary = .wanxiang) {
        self.keyboard = keyboard
        self.scheme = scheme
        self.fuzzy = fuzzy
        self.useGrammar = useGrammar
        self.dictionary = dictionary
    }

    var translatorDictionary: String {
        switch dictionary {
        case .wanxiang: Self.dictionaryName
        case .rimeIce: Self.rimeIceDictionaryName
        }
    }

    /// The manifest for `sugu_ice`, written next to the downloaded tables.
    public static func rimeIceManifest(version: String) -> String {
        """
        # Generated by Sugu. Data: rime-ice (GPL-3.0), github.com/iDvel/rime-ice, downloaded by the user.
        ---
        name: \(rimeIceDictionaryName)
        version: "\(version)"
        sort: by_weight
        use_preset_vocabulary: false
        import_tables:
        \(rimeIceTables.map { "  - \(rimeIceFolder)/\($0)" }.joined(separator: "\n"))
        ...

        """
    }

    /// librime option that turns on the filter for a script.
    public static func option(for script: ChineseScript) -> String? {
        switch script {
        case .simplified: nil
        case .traditional: "s2t"
        case .traditionalTaiwan: "s2tw"
        case .traditionalHongKong: "s2hk"
        case .japanese: "s2jp"
        }
    }

    /// The filter that offers emoji after the words that name them.
    static let emojiOption = "emoji"

    static let scriptFilters: [(option: String, config: String)] = [
        ("s2t", "s2t.json"), ("s2tw", "s2twp.json"), ("s2hk", "s2hk.json"), ("s2jp", RimeSharedData.japaneseFormsConfig),
    ]

    /// Spelling-rule sections, applied in order: tone marks are stripped,
    /// fuzzy rules act on whole syllables, then the scheme maps syllables to
    /// keys. Scheme rules come from wanxiang's `lite` algebra (CC-BY-4.0).
    var algebraPatches: [String] {
        guard keyboard == .pinyin else { return ["sugu_algebra:/tones"] }
        var patches = ["sugu_algebra:/toneless"]
        patches += FuzzyPinyin.allCases.filter(fuzzy.contains).map { "wanxiang_algebra:/\($0.algebraSection)" }
        patches.append("wanxiang_algebra:/lite/\(scheme.algebraSection)")
        return patches
    }

    public func yaml(version: String) -> String {
        var lines = [
            "# Generated by Sugu from its settings; edits are overwritten.",
            "schema:",
            "  schema_id: \(Self.schemaID)",
            "  name: Sugu",
            "  version: \(quoted(version))",
            "switches:",
            "  - name: ascii_mode",
            "    reset: 0",
        ]
        for filter in Self.scriptFilters {
            lines += ["  - name: \(filter.option)", "    reset: 1"]
        }
        lines += ["  - name: \(Self.emojiOption)", "    reset: 1"]
        lines += [
            "engine:",
            "  processors:",
            "    - speller",
            "    - navigator",
            "    - express_editor",
            "  segmentors:",
            "    - abc_segmentor",
            "    - fallback_segmentor",
            "  translators:",
            "    - script_translator",
            "  filters:",
        ]
        lines += Self.scriptFilters.map { "    - simplifier@\($0.option)" }
        // After the script filters, so it reads the words as shown; the
        // table holds Simplified and Traditional words.
        lines += ["    - simplifier@\(Self.emojiOption)"]
        lines += [
            "    - uniquifier",
            "speller:",
            "  alphabet: zyxwvutsrqponmlkjihgfedcba\(keyboard == .zhuyin ? "12345" : "")",
            "  delimiter: \" '\"",
            "  algebra:",
            "    __patch:",
        ]
        lines += algebraPatches.map { "      - \($0)" }
        lines += [
            "translator:",
            "  dictionary: \(translatorDictionary)",
            "  prism: \(translatorDictionary)",
            // Sugu's learned words, generated read-only: librime does not
            // learn on its own (decision D-003, D-025).
            "  enable_user_dict: true",
            "  user_dict: \(RimeUserDictionary.name)",
            "  db_class: stabledb",
            "  enable_completion: true",
            "  enable_sentence: true",
            "  initial_quality: 3",
            "  max_homophones: 8",
        ]
        if useGrammar {
            lines += [
                "  contextual_suggestions: false",
                "grammar:",
                "  language: \(Self.grammarLanguage)",
                "  collocation_max_length: 6",
                "  collocation_min_length: 2",
                "  collocation_penalty: -14",
                "  non_collocation_penalty: -6",
                "  weak_collocation_penalty: -100",
                "  rear_penalty: -18",
            ]
        }
        for filter in Self.scriptFilters {
            lines += ["\(filter.option):", "  opencc_config: \(filter.config)", "  option_name: \(filter.option)"]
        }
        lines += ["\(Self.emojiOption):", "  opencc_config: \(EmojiNames.config)", "  option_name: \(Self.emojiOption)", "  tips: none"]
        lines += ["menu:", "  page_size: 10", ""]
        return lines.joined(separator: "\n")
    }

    private func quoted(_ value: String) -> String {
        "\"" + value.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}

extension PinyinScheme {
    /// Section name in wanxiang's algebra file.
    var algebraSection: String {
        switch self {
        case .fullPinyin: "全拼"
        case .xiaohe: "小鹤双拼"
        case .ziranma: "自然码"
        case .microsoft: "微软双拼"
        case .sogou: "搜狗双拼"
        case .ziguang: "紫光双拼"
        case .abc: "智能ABC"
        case .pinyinPlusPlus: "拼音加加"
        }
    }
}

extension FuzzyPinyin {
    var algebraSection: String {
        switch self {
        case .zZh: "模糊音_z_zh"
        case .cCh: "模糊音_c_ch"
        case .sSh: "模糊音_s_sh"
        case .nL: "模糊音_nl"
        case .fH: "模糊音_hf"
        case .rL: "模糊音_rl"
        case .rY: "模糊音_ry"
        case .kG: "模糊音_kg"
        case .enEng: "模糊音_en_eng"
        case .inIng: "模糊音_in_ing"
        }
    }
}

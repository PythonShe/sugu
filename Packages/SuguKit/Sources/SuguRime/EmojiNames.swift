import Foundation

/// Chinese words that offer an emoji after them, from CLDR's emoji
/// annotations (Unicode-DFS-2016), as an OpenCC text table that librime's
/// `simplifier@emoji` reads: 微笑 → 😊 follows 微笑 in the candidates.
public enum EmojiNames {
    public static let table = "emoji.txt"
    public static let config = "emoji.json"
    /// Emoji that follow one word: each pushes the word's homophones down
    /// a row.
    static let emojiPerWord = 1

    /// The table from annotation files (`common/annotations/zh.xml` and
    /// `zh_Hant.xml`). A word offers an emoji when it is the emoji's name,
    /// or one of its keywords of two or more characters: single characters
    /// (脸, 好, 手) name too many emoji to be worth a candidate each time
    /// they are typed. Names come first, then keywords in CLDR's order.
    public static func table(fromAnnotations files: [Data]) -> String {
        var names: [String: [String]] = [:]
        var keywords: [String: [String]] = [:]
        for data in files {
            let parser = AnnotationParser()
            let xml = XMLParser(data: data)
            xml.delegate = parser
            xml.parse()
            for annotation in parser.annotations {
                let emoji = presented(annotation.emoji)
                if annotation.isName {
                    add(emoji, for: annotation.text, to: &names)
                } else {
                    for keyword in annotation.text.split(separator: "|") {
                        let word = keyword.trimmingCharacters(in: .whitespaces)
                        if word.count >= 2 { add(emoji, for: word, to: &keywords) }
                    }
                }
            }
        }
        var lines: [String] = []
        for word in Set(names.keys).union(keywords.keys).sorted() where isHan(word) {
            var emoji: [String] = []
            for candidate in (names[word] ?? []) + (keywords[word] ?? []) where !emoji.contains(candidate) {
                emoji.append(candidate)
            }
            lines.append("\(word)\t\(([word] + emoji.prefix(emojiPerWord)).joined(separator: " "))")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// The OpenCC configuration for the table: whole words, longest first.
    public static let configuration = """
    {
      "name": "Chinese words to emoji, generated by Sugu from CLDR annotations",
      "segmentation": {"type": "mmseg", "dict": {"type": "text", "file": "\(table)"}},
      "conversion_chain": [{"dict": {"type": "text", "file": "\(table)"}}]
    }

    """

    private static func add(_ emoji: String, for word: String, to map: inout [String: [String]]) {
        map[word, default: []].append(emoji)
    }

    /// Characters that librime writes from pinyin.
    private static func isHan(_ word: String) -> Bool {
        word.unicodeScalars.allSatisfy { $0.properties.isIdeographic }
    }

    /// The emoji as fully qualified: CLDR leaves out the presentation
    /// selector, without which symbols that draw as text unless asked (❤,
    /// ♂ in 🙆‍♂️, # in #️⃣) show as text or as separate pieces.
    private static func presented(_ emoji: String) -> String {
        let scalars = Array(emoji.unicodeScalars)
        var result = String.UnicodeScalarView()
        for (index, scalar) in scalars.enumerated() {
            result.append(scalar)
            let next = index + 1 < scalars.count ? scalars[index + 1] : nil
            if scalar.properties.isEmoji, !scalar.properties.isEmojiPresentation, !scalar.properties.isEmojiModifier,
               next != "\u{FE0F}", next?.properties.isEmojiModifier != true {
                result.append("\u{FE0F}")
            }
        }
        return String(result)
    }
}

private final class AnnotationParser: NSObject, XMLParserDelegate {
    struct Annotation {
        var emoji: String
        var isName: Bool
        var text: String
    }

    private(set) var annotations: [Annotation] = []
    private var current: Annotation?

    func parser(_ parser: XMLParser, didStartElement element: String, namespaceURI: String?, qualifiedName: String?, attributes: [String: String] = [:]) {
        guard element == "annotation", let emoji = attributes["cp"] else { return }
        current = Annotation(emoji: emoji, isName: attributes["type"] == "tts", text: "")
    }

    func parser(_ parser: XMLParser, foundCharacters string: String) {
        current?.text += string
    }

    func parser(_ parser: XMLParser, didEndElement element: String, namespaceURI: String?, qualifiedName: String?) {
        guard element == "annotation", var annotation = current else { return }
        annotation.text = annotation.text.trimmingCharacters(in: .whitespacesAndNewlines)
        if !annotation.text.isEmpty { annotations.append(annotation) }
        current = nil
    }
}

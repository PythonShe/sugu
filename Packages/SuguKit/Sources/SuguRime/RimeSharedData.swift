import Foundation

/// Writes the bundled, read-only librime data directory: configuration,
/// the dictionary manifest, spelling rules, OpenCC tables, and dictionary
/// sources for precompilation. Used by `sugu-tool build-data`.
public enum RimeSharedData {
    /// Tables imported into Sugu's Chinese dictionary, in wanxiang's order.
    public static let importedTables = ["zi", "jichu", "cuoyin", "duoyin", "diming", "mingren", "yiren"]

    public static func write(to directory: URL, wanxiang: URL, openCC: URL, version: String) throws {
        let fm = FileManager.default
        try fm.createDirectory(at: directory.appendingPathComponent("dicts"), withIntermediateDirectories: true)
        for table in importedTables {
            let name = "\(table).dict.yaml"
            let target = directory.appendingPathComponent("dicts/\(name)")
            try? fm.removeItem(at: target)
            try fm.copyItem(at: wanxiang.appendingPathComponent("dicts/\(name)"), to: target)
        }
        let algebra = directory.appendingPathComponent("wanxiang_algebra.yaml")
        try? fm.removeItem(at: algebra)
        try fm.copyItem(at: wanxiang.appendingPathComponent("wanxiang_algebra.yaml"), to: algebra)

        let openCCTarget = directory.appendingPathComponent("opencc")
        try? fm.removeItem(at: openCCTarget)
        try fm.copyItem(at: openCC, to: openCCTarget)

        try defaultConfig.write(to: directory.appendingPathComponent("default.yaml"), atomically: true, encoding: .utf8)
        try dictionaryManifest(version: version).write(to: directory.appendingPathComponent("\(RimeSchema.dictionaryName).dict.yaml"), atomically: true, encoding: .utf8)
        try tonelessAlgebra.write(to: directory.appendingPathComponent("sugu_algebra.yaml"), atomically: true, encoding: .utf8)
        try RimeSchema().yaml(version: version).write(to: directory.appendingPathComponent("\(RimeSchema.schemaID).schema.yaml"), atomically: true, encoding: .utf8)
    }

    static let defaultConfig = """
    # Generated by Sugu.
    config_version: "1"
    schema_list:
      - schema: \(RimeSchema.schemaID)
    menu:
      page_size: 100

    """

    static func dictionaryManifest(version: String) -> String {
        """
        # Generated by Sugu. Data: rime-wanxiang (CC-BY-4.0), github.com/amzxyz/rime_wanxiang
        ---
        name: \(RimeSchema.dictionaryName)
        version: "\(version)"
        sort: by_weight
        use_preset_vocabulary: false
        import_tables:
        \(importedTables.map { "  - dicts/\($0)" }.joined(separator: "\n"))
        ...

        """
    }

    /// Strips tone marks so syllables reach the scheme rules as plain
    /// letters, with ü written as v.
    static let tonelessAlgebra = """
    # Generated by Sugu.
    toneless:
      __append:
        - xlit/āáǎàōóǒòēéěèīíǐìūúǔùǖǘǚǜüńňǹḿ/aaaaooooeeeeiiiiuuuuvvvvvnnnm/

    """
}

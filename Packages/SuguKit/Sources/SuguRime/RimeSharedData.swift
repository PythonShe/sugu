import Foundation
import SuguCore

/// Writes the bundled, read-only librime data directory: configuration,
/// the dictionary manifest, spelling rules, OpenCC tables, and dictionary
/// sources for precompilation. Used by `sugu-tool build-data`.
///
/// The schema is not part of it: Sugu writes it into the user directory
/// from settings, and librime moves a user schema to its trash when the
/// shared directory holds a copy with a higher version.
public enum RimeSharedData {
    /// Tables imported into Sugu's Chinese dictionary, in wanxiang's order;
    /// `scripts/fetch-data.sh` downloads them (`WANXIANG_DICTS`).
    public static let importedTables = ["zi", "jichu", "cuoyin", "duoyin", "diming", "mingren", "yiren"]

    /// `emojiAnnotations` are CLDR's Chinese annotation files (EmojiNames).
    public static func write(to directory: URL, wanxiang: URL, openCC: URL, emojiAnnotations: [Data], version: String) throws {
        let fm = FileManager.default
        try fm.createDirectory(at: directory.appendingPathComponent("dicts"), withIntermediateDirectories: true)
        for table in importedTables {
            let name = "\(table).dict.yaml"
            let target = directory.appendingPathComponent("dicts/\(name)")
            try? fm.removeItem(at: target)
            try fm.copyItem(at: wanxiang.appendingPathComponent("dicts/\(name)"), to: target)
        }
        let algebra = directory.appendingPathComponent("wanxiang_algebra.yaml")
        try? fm.removeItem(at: algebra)
        try fm.copyItem(at: wanxiang.appendingPathComponent("wanxiang_algebra.yaml"), to: algebra)

        let openCCTarget = directory.appendingPathComponent("opencc")
        try? fm.removeItem(at: openCCTarget)
        try fm.copyItem(at: openCC, to: openCCTarget)
        try japaneseForms.write(to: openCCTarget.appendingPathComponent(japaneseFormsConfig), atomically: true, encoding: .utf8)
        try EmojiNames.table(fromAnnotations: emojiAnnotations)
            .write(to: openCCTarget.appendingPathComponent(EmojiNames.table), atomically: true, encoding: .utf8)
        try EmojiNames.configuration.write(to: openCCTarget.appendingPathComponent(EmojiNames.config), atomically: true, encoding: .utf8)

        try defaultConfig.write(to: directory.appendingPathComponent("default.yaml"), atomically: true, encoding: .utf8)
        let zi = try String(contentsOf: wanxiang.appendingPathComponent("dicts/zi.dict.yaml"), encoding: .utf8)
        try syllableTable(version: version, characters: Lexicon.syllableCharacters(fromRimeDictionary: zi))
            .write(to: directory.appendingPathComponent("dicts/\(syllableTableName).dict.yaml"), atomically: true, encoding: .utf8)
        try dictionaryManifest(version: version).write(to: directory.appendingPathComponent("\(RimeSchema.dictionaryName).dict.yaml"), atomically: true, encoding: .utf8)
        try spellingAlgebra.write(to: directory.appendingPathComponent("sugu_algebra.yaml"), atomically: true, encoding: .utf8)
    }

    /// OpenCC has no Simplified → Japanese kanji configuration; this chains
    /// its Simplified → Traditional tables with its Japanese variant table.
    static let japaneseFormsConfig = "s2jp.json"
    static let japaneseForms = """
    {
      "name": "Simplified Chinese to Japanese Kanji (Shinjitai), generated by Sugu",
      "segmentation": {"type": "mmseg", "dict": {"type": "ocd2", "file": "STPhrases.ocd2"}},
      "conversion_chain": [
        {"dict": {"type": "group", "dicts": [{"type": "ocd2", "file": "STPhrases.ocd2"}, {"type": "ocd2", "file": "STCharacters.ocd2"}]}},
        {"dict": {"type": "ocd2", "file": "JPVariants.ocd2"}}
      ]
    }

    """

    static let defaultConfig = """
    # Generated by Sugu.
    config_version: "1"
    schema_list:
      - schema: \(RimeSchema.schemaID)
    menu:
      page_size: 10

    """

    static func dictionaryManifest(version: String) -> String {
        """
        # Generated by Sugu. Data: rime-wanxiang (CC-BY-4.0), github.com/amzxyz/rime_wanxiang
        ---
        name: \(RimeSchema.dictionaryName)
        version: "\(version)"
        sort: by_weight
        use_preset_vocabulary: false
        import_tables:
        \((importedTables + [syllableTableName]).map { "  - dicts/\($0)" }.joined(separator: "\n"))
        ...

        """
    }

    static let syllableTableName = "sugu_syllables"

    /// One entry per toneless syllable, so the syllabary holds every
    /// syllable without tone marks (wanxiang's are mostly toned) and the
    /// user dictionary can be written in the syllables the user typed. At
    /// weight 0 they never rank, and imported last, an entry that repeats a
    /// wanxiang one is the copy librime drops.
    static func syllableTable(version: String, characters: [String: String]) -> String {
        """
        # Generated by Sugu from rime-wanxiang's zi table (CC-BY-4.0).
        ---
        name: \(syllableTableName)
        version: "\(version)"
        sort: original
        ...
        \(characters.sorted { $0.key < $1.key }.map { "\($0.value)\t\($0.key)\t0" }.joined(separator: "\n"))

        """
    }

    /// Sugu's spelling rules. `toneless` strips tone marks so syllables
    /// reach the pinyin scheme rules as plain letters, with ü written as v;
    /// `tones` writes each syllable as the code the Zhuyin engine types,
    /// pinyin then the tone's digit.
    static let spellingAlgebra = """
    # Generated by Sugu.
    toneless:
      __append:
        - xlit/āáǎàōóǒòēéěèīíǐìūúǔùǖǘǚǜüńňǹḿ/aaaaooooeeeeiiiiuuuuvvvvvnnnm/
    tones:
      __append:
    \(Zhuyin.toneRules.map { "    - \($0)" }.joined(separator: "\n"))

    """
}
